import {
  pgTable,
  uuid,
  varchar,
  text,
  numeric,
  boolean,
  timestamp,
  integer,
  jsonb,
} from 'drizzle-orm/pg-core';

export const profiles = pgTable('profiles', {
  userId: uuid('user_id').primaryKey(),
  username: varchar('username', { length: 255 }).unique(),
  displayName: varchar('display_name', { length: 255 }),
  bio: text('bio'),
  avatarStoragePath: text('avatar_storage_path'),
  bannerStoragePath: text('banner_storage_path'),
  websiteUrl: text('website_url'),
  countryCode: varchar('country_code', { length: 5 }),
  preferredLanguageCode: varchar('preferred_language_code', { length: 10 }),
  accountStatus: varchar('account_status', { length: 30 }).default('active'),
  isVerified: boolean('is_verified').default(false),
  createdAt: timestamp('created_at', { withTimezone: true }).defaultNow(),
  updatedAt: timestamp('updated_at', { withTimezone: true }).defaultNow(),
});

export const artistProfiles = pgTable('artist_profiles', {
  id: uuid('id').defaultRandom().primaryKey(),
  artistName: varchar('artist_name', { length: 255 }).notNull(),
  artistHandle: varchar('artist_handle', { length: 255 }).unique(),
  artistType: varchar('artist_type', { length: 50 }),
  bioEn: text('bio_en'),
  bioRw: text('bio_rw'),
  avatarPath: text('avatar_path'),
  bannerPath: text('banner_path'),
  websiteUrl: text('website_url'),
  countryCode: varchar('country_code', { length: 5 }),
  primaryLanguageCode: varchar('primary_language_code', { length: 10 }),
  createdByUserId: uuid('created_by_user_id'),
  primaryContactUserId: uuid('primary_contact_user_id'),
  recordStatus: varchar('record_status', { length: 30 }).default('active'),
  verificationStatus: varchar('verification_status', { length: 30 }).default('pending'),
  approvalStatus: varchar('approval_status', { length: 30 }).default('pending'),
  isPublic: boolean('is_public').default(true),
  createdAt: timestamp('created_at', { withTimezone: true }).defaultNow(),
  updatedAt: timestamp('updated_at', { withTimezone: true }).defaultNow(),
});

export const creatorChannels = pgTable('creator_channels', {
  id: uuid('id').defaultRandom().primaryKey(),
  channelName: varchar('channel_name', { length: 255 }).notNull(),
  channelHandle: varchar('channel_handle', { length: 255 }).unique(),
  channelType: varchar('channel_type', { length: 50 }),
  descriptionEn: text('description_en'),
  descriptionRw: text('description_rw'),
  avatarPath: text('avatar_path'),
  bannerPath: text('banner_path'),
  countryCode: varchar('country_code', { length: 5 }),
  ownerUserId: uuid('owner_user_id'),
  approvalStatus: varchar('approval_status', { length: 30 }).default('approved'),
  isPublic: boolean('is_public').default(true),
  createdAt: timestamp('created_at', { withTimezone: true }).defaultNow(),
  updatedAt: timestamp('updated_at', { withTimezone: true }).defaultNow(),
});

export const videos = pgTable('videos', {
  id: uuid('id').defaultRandom().primaryKey(),
  creatorChannelId: uuid('creator_channel_id').references(() => creatorChannels.id),
  artistProfileId: uuid('artist_profile_id').references(() => artistProfiles.id),
  createdByUserId: uuid('created_by_user_id'),
  videoType: varchar('video_type', { length: 50 }).default('music_video'),
  title: varchar('title', { length: 255 }).notNull(),
  description: text('description'),
  slug: varchar('slug', { length: 255 }),
  durationSeconds: integer('duration_seconds').default(0),
  sourceMediaAssetId: uuid('source_media_asset_id'),
  thumbnailMediaAssetId: uuid('thumbnail_media_asset_id'),
  visibility: varchar('visibility', { length: 20 }).default('public'),
  publicationStatus: varchar('publication_status', { length: 30 }).default('published'),
  processingStatus: varchar('processing_status', { length: 30 }).default('ready'),
  moderationStatus: varchar('moderation_status', { length: 30 }).default('approved'),
  isFree: boolean('is_free').default(false),
  isPaywalled: boolean('is_paywalled').default(true),
  allowComments: boolean('allow_comments').default(true),
  allowEmbedding: boolean('allow_embedding').default(true),
  ageRestricted: boolean('age_restricted').default(false),
  scheduledAt: timestamp('scheduled_at', { withTimezone: true }),
  publishedAt: timestamp('published_at', { withTimezone: true }).defaultNow(),
  metadata: jsonb('metadata').default({}),
  createdAt: timestamp('created_at', { withTimezone: true }).defaultNow(),
  updatedAt: timestamp('updated_at', { withTimezone: true }).defaultNow(),
});

export const musicTracks = pgTable('music_tracks', {
  id: uuid('id').defaultRandom().primaryKey(),
  creatorChannelId: uuid('creator_channel_id').references(() => creatorChannels.id),
  createdByUserId: uuid('created_by_user_id'),
  title: varchar('title', { length: 255 }).notNull(),
  titleNative: varchar('title_native', { length: 255 }),
  slug: varchar('slug', { length: 255 }),
  description: text('description'),
  trackStatus: varchar('track_status', { length: 30 }).default('published'),
  visibility: varchar('visibility', { length: 20 }).default('public'),
  primaryLanguageCode: varchar('primary_language_code', { length: 10 }).default('rw'),
  durationMs: integer('duration_ms').default(0),
  explicitContent: boolean('explicit_content').default(false),
  publishedAt: timestamp('published_at', { withTimezone: true }).defaultNow(),
  metadata: jsonb('metadata').default({}),
  createdAt: timestamp('created_at', { withTimezone: true }).defaultNow(),
  updatedAt: timestamp('updated_at', { withTimezone: true }).defaultNow(),
});

export const financialTransactions = pgTable('financial_transactions', {
  id: uuid('id').defaultRandom().primaryKey(),
  userId: uuid('user_id'),
  artistId: uuid('artist_id').references(() => artistProfiles.id),
  transactionType: varchar('transaction_type', { length: 50 }).notNull(),
  amount: numeric('amount', { precision: 15, scale: 2 }).notNull(),
  vatAmount: numeric('vat_amount', { precision: 15, scale: 2 }).default('0.00'),
  artistShare: numeric('artist_share', { precision: 15, scale: 2 }).default('0.00'),
  platformShare: numeric('platform_share', { precision: 15, scale: 2 }).default('0.00'),
  currency: varchar('currency', { length: 10 }).default('RWF'),
  status: varchar('status', { length: 30 }).default('pending'),
  referenceId: uuid('reference_id'),
  metadata: jsonb('metadata').default({}),
  createdAt: timestamp('created_at', { withTimezone: true }).defaultNow(),
});

export const notifications = pgTable('notifications', {
  id: uuid('id').defaultRandom().primaryKey(),
  recipientUserId: uuid('recipient_user_id'),
  actorUserId: uuid('actor_user_id'),
  notificationType: varchar('notification_type', { length: 50 }).notNull(),
  title: varchar('title', { length: 255 }).notNull(),
  message: text('message').notNull(),
  contentType: varchar('content_type', { length: 50 }),
  contentId: uuid('content_id'),
  isRead: boolean('is_read').default(false),
  actionUrl: varchar('action_url', { length: 255 }),
  metadata: jsonb('metadata').default({}),
  createdAt: timestamp('created_at', { withTimezone: true }).defaultNow(),
  updatedAt: timestamp('updated_at', { withTimezone: true }).defaultNow(),
});
